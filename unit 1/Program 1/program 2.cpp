#include <iostream>
using namespace std;

int main() {

    // Store student's marks
    int marks = 45;

    // Check whether marks are 40 or more
    if (marks >= 40) {

        // Execute when condition is true
        cout << "Pass";

    } else {

        // Execute when condition is false
        cout << "Fail";
    }

    // End the program
    return 0;
}

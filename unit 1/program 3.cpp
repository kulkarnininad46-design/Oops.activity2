#include <iostream>
using namespace std;

int main() {

    // Create an array to store marks of 5 students
    int marks[5] = {78, 82, 91, 67, 88};

    // Loop through all 5 elements of the array
    for (int i = 0; i < 5; i++) {

        // Display the current array element
        cout << marks[i] << " ";
    }

    // End the program
    return 0;
}
